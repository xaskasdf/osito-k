/* Verify a PKCS#1 v1.5 SHA-256 signature.
 *
 *   sig, sig_len: the raw signature bytes (typically 256 = RSA-2048).
 *   n,   n_len  : modulus, big-endian.
 *   e,   e_len  : public exponent, big-endian (typically 0x01 0x00 0x01).
 *   hash[32]    : the SHA-256 digest of the signed data.
 *
 * Returns 0 on success, -1 on any failure (bad length, padding,
 * digest mismatch). */
/* Common path for PKCS#1 v1.5 verify against any hash algorithm
 * whose DigestInfo prefix we know.  `di_prefix` covers everything
 * before the hash bytes (the SEQUENCE header + AlgorithmIdentifier
 * + OCTET STRING tag+length).  T = di_prefix ‖ hash, so
 * T_len = di_prefix_len + hash_len. */
static int rsa_verify_inner(const uint8_t *sig, uint32_t sig_len,
                            const uint8_t *n,   uint32_t n_len,
                            const uint8_t *e,   uint32_t e_len,
                            const uint8_t *hash, uint32_t hash_len,
                            const uint8_t *di_prefix, uint32_t di_prefix_len)
{
    if (sig_len != n_len) return -1;
    if (n_len == 0 || n_len > BN_MAX_LIMBS * 8) return -1;
    if (e_len == 0 || e_len > 8)            return -1;
    uint32_t limbs = (n_len + 7U) / 8U;

    bn_t S, N, M;
    if (bn_from_be(&S, sig, sig_len) < 0) return -1;
    if (bn_from_be(&N, n,   n_len)   < 0) return -1;

    uint64_t exp = 0;
    for (uint32_t i = 0; i < e_len; i++) exp = (exp << 8) | e[i];
    if (exp == 0) return -1;
    if (bn_cmp(&S, &N, limbs) >= 0) return -1;

    bn_mod_pow_small_e(&M, &S, exp, &N, limbs);

    uint8_t em_full[BN_MAX_LIMBS * 8];
    bn_to_be(&M, em_full, limbs);
    const uint8_t *em = em_full + (limbs * 8U - sig_len);

    /* EM = 0x00 || 0x01 || 0xFF...0xFF || 0x00 || T  (RFC 8017 §9.2). */
    if (em[0] != 0x00 || em[1] != 0x01) return -1;
    uint32_t t_len = di_prefix_len + hash_len;
    if (t_len + 3 > sig_len) return -1;
    uint32_t t_offset = sig_len - t_len;
    if (t_offset < 11) return -1;          /* PS ≥ 8 octets */
    for (uint32_t i = 2; i < t_offset - 1; i++)
        if (em[i] != 0xFF) return -1;
    if (em[t_offset - 1] != 0x00) return -1;
    for (uint32_t i = 0; i < di_prefix_len; i++)
        if (em[t_offset + i] != di_prefix[i]) return -1;
    uint8_t diff = 0;
    for (uint32_t i = 0; i < hash_len; i++)
        diff |= (uint8_t)(em[t_offset + di_prefix_len + i] ^ hash[i]);
    if (diff != 0) return -1;
    return 0;
}

/* SHA-256 DigestInfo prefix (19 bytes), then 32-byte hash. */
static const uint8_t sha256_di_prefix[19] = {
    0x30,0x31,0x30,0x0d,0x06,0x09,0x60,0x86,0x48,
    0x01,0x65,0x03,0x04,0x02,0x01,0x05,0x00,0x04,0x20
};

/* SHA-384 DigestInfo prefix (19 bytes), then 48-byte hash.  OID
 * arc differs from SHA-256 at byte 14 (0x02 vs 0x01) and the
 * OCTET STRING length at byte 18 (0x30 vs 0x20).  Outer SEQUENCE
 * length grows from 0x31 to 0x41 to accommodate the bigger hash. */
static const uint8_t sha384_di_prefix[19] = {
    0x30,0x41,0x30,0x0d,0x06,0x09,0x60,0x86,0x48,
    0x01,0x65,0x03,0x04,0x02,0x02,0x05,0x00,0x04,0x30
};

int rsa_pkcs1_v15_sha256_verify(const uint8_t *sig, uint32_t sig_len,
                                 const uint8_t *n, uint32_t n_len,
                                 const uint8_t *e, uint32_t e_len,
                                 const uint8_t hash[32])
{
    return rsa_verify_inner(sig, sig_len, n, n_len, e, e_len,
                            hash, 32, sha256_di_prefix, 19);
}

int rsa_pkcs1_v15_sha384_verify(const uint8_t *sig, uint32_t sig_len,
                                 const uint8_t *n, uint32_t n_len,
                                 const uint8_t *e, uint32_t e_len,
                                 const uint8_t hash[48])
{
    return rsa_verify_inner(sig, sig_len, n, n_len, e, e_len,
                            hash, 48, sha384_di_prefix, 19);
}

