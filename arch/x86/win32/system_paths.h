#ifndef OSITO_WIN32_SYSTEM_PATHS_H
#define OSITO_WIN32_SYSTEM_PATHS_H

/* Guest paths and backing directories on the mounted OsitoFS. Installers own
 * the runtime files; no redistributable is linked into the kernel. */
#define WIN32_WINDOWS_RELATIVE "Windows"
#define WIN32_SYSTEM32_RELATIVE WIN32_WINDOWS_RELATIVE "\\System32"
#define WIN32_SYSWOW64_RELATIVE WIN32_WINDOWS_RELATIVE "\\SysWOW64"
#define WIN32_WINDOWS_DIRECTORY "C:\\" WIN32_WINDOWS_RELATIVE
#define WIN32_SYSTEM32_DIRECTORY "C:\\" WIN32_SYSTEM32_RELATIVE
#define WIN32_SYSWOW64_DIRECTORY "C:\\" WIN32_SYSWOW64_RELATIVE
#define WIN32_DEFAULT_PATH WIN32_SYSTEM32_DIRECTORY ";" WIN32_WINDOWS_DIRECTORY

#endif
