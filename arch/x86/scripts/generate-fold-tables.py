"""Generate Unicode normalization facts and native Win32 digit/ligature maps.

Run with Python 3.14 (Unicode 16.0.0) on Windows. No installed data is changed.
Unicode normalization data: https://www.unicode.org/Public/16.0.0/ucd/
"""
from pathlib import Path
import ctypes as C, json, sys, unicodedata as U
assert U.unidata_version=='16.0.0',U.unidata_version
root=Path(__file__).resolve().parents[3]
out=root/'arch/x86/build/msgwait-20261003/steam-client-abi-research';out.mkdir(exist_ok=True)
fold=C.WinDLL('kernel32',use_last_error=True).FoldStringW
fold.argtypes=[C.c_uint,C.c_void_p,C.c_int,C.c_void_p,C.c_int];fold.restype=C.c_int
source=(C.c_ushort*8)();target=(C.c_ushort*32)();maps={0x80:[],0x2000:[]}
decomposition=[];pool=[];combining=[];composition=[]
for cp in range(0x110000):
    if 0xd800<=cp<=0xdfff:continue
    if cp<0x10000:source[0]=cp;source[1]=0;length=1
    else:
        v=cp-0x10000;source[0]=0xd800+(v>>10);source[1]=0xdc00+(v&1023);length=2
    original=list(source)[:length]
    for flags in maps:
        count=fold(flags,source,length,target,32);assert count>0,(cp,flags,C.get_last_error())
        units=list(target)[:count]
        if units!=original:
            scalars=[ord(c) for c in bytes().join(v.to_bytes(2,'little') for v in units).decode('utf-16-le')]
            maps[flags].append([cp,scalars])
    ch=chr(cp);ccc=U.combining(ch)
    if ccc:
        # A recognized non-starter sorts through the known CCC 240/1
        # sentinels. An unrecognized character leaves the first in place.
        sample=('\u0345'+ch+'\u0334').encode('utf-16-le')
        C.memmove(source,sample,len(sample))
        count=fold(0x40,source,len(sample)//2,target,32)
        assert count>0
        if target[0]!=0x345:combining.append([cp,ccc])
        for i,value in enumerate(original):source[i]=value
    if 0xac00<=cp<=0xd7a3:continue # Algorithmic Hangul, no table required.
    text=U.decomposition(ch)
    if not text:continue
    parts=text.split();compat=parts[0].startswith('<')
    if compat:parts=parts[1:]
    points=[int(p,16) for p in parts]
    count=fold(0x50 if compat else 0x40,source,length,target,32)
    assert count>0
    if list(target)[:count]==original:continue
    decomposition.append([cp,len(pool),len(points),int(compat)]);pool+=points
    if not compat and len(points)==2 and U.normalize('NFC',''.join(map(chr,points)))==ch:
        pair=''.join(map(chr,points)).encode('utf-16-le');C.memmove(source,pair,len(pair))
        count=fold(0x20,source,len(pair)//2,target,32)
        if list(target)[:count]==original:composition.append([*points,cp])
    if cp in (0xffff,0x1ffff):print('scanned',hex(cp),flush=True)
data={'unicode':U.unidata_version,'windows':list(sys.getwindowsversion()),'digits':maps[0x80],'ligatures':maps[0x2000]}
(out/'fold-native-mappings.json').write_text(json.dumps(data,indent=2)+'\n')
lines=['/* Generated by scripts/generate-fold-tables.py. Unicode 16.0.0 facts',
       ' * filtered to the Windows normalization profile; digit and ligature',
       ' * mappings characterized through native FoldStringW (Windows '+str(sys.getwindowsversion().build)+').',
       ' * Unicode data license: UNICODE-LICENSE.txt. */']
def array(ctype,name,rows):
    lines.append('static const '+ctype+' '+name+'[] = {')
    lines.extend('    {'+','.join(hex(n) for n in row)+'},' for row in rows)
    lines.append('};')
lines.append('static const uint32_t fold_decomposition_values[] = {')
for i in range(0,len(pool),12):lines.append('    '+','.join(hex(n) for n in pool[i:i+12])+',')
lines.append('};')
array('fold_decomposition_t','fold_decompositions',decomposition)
array('fold_combining_t','fold_combining_classes',combining)
array('fold_composition_t','fold_compositions',sorted(composition))
for flag,name in [(0x80,'digits'),(0x2000,'ligatures')]:
    assert all(len(row[1])<=4 for row in maps[flag])
    if flag==0x80:assert all(len(row[1])==1 and row[1][0]<0x10000 for row in maps[flag])
    lines.append('static const fold_mapping_t fold_'+name+'[] = {')
    for cp,points in maps[flag]:lines.append('    {'+hex(cp)+','+str(len(points))+',{'+','.join(hex(n) for n in points)+'}},')
    lines.append('};')
header=root/'arch/x86/win32/fold_tables.h';header.write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
print(json.dumps({'header_bytes':header.stat().st_size,'decompositions':len(decomposition),'combining':len(combining),'compositions':len(composition),'digits':len(maps[0x80]),'ligatures':len(maps[0x2000])}),flush=True)
