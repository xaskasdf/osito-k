#!/usr/bin/env python3
"""Record non-linguistic Windows casing behavior, not Windows code or NLS files."""
import argparse
import ctypes
import os
from pathlib import Path
import platform


def ranges(pairs):
    result = []
    i = 0
    while i < len(pairs):
        first, mapped = pairs[i]
        delta = mapped - first
        step = 1
        if i + 1 < len(pairs):
            next_char, next_mapped = pairs[i + 1]
            if next_mapped - next_char == delta and next_char - first in (1, 2):
                step = next_char - first
        last = first
        i += 1
        while i < len(pairs) and pairs[i] == (last + step, last + step + delta):
            last += step
            i += 1
        result.append((first, last, delta, step))
    return result


def sample(function):
    function.argtypes = [ctypes.c_void_p, ctypes.c_uint32]
    function.restype = ctypes.c_uint32
    buffer = (ctypes.c_uint16 * 2)()
    pairs = []
    for code in range(0x110000):
        count = 1 if code < 0x10000 else 2
        buffer[0] = code if count == 1 else 0xD800 + ((code - 0x10000) >> 10)
        buffer[1] = 0 if count == 1 else 0xDC00 + ((code - 0x10000) & 1023)
        assert function(buffer, count) == count
        if count == 1:
            mapped = buffer[0]
        else:
            assert 0xD800 <= buffer[0] <= 0xDBFF and 0xDC00 <= buffer[1] <= 0xDFFF
            mapped = 0x10000 + ((buffer[0] - 0xD800) << 10) + buffer[1] - 0xDC00
        if mapped != code:
            pairs.append((code, mapped))
    return ranges(pairs)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if os.name != "nt":
        parser.error("the reference oracle requires Windows")
    user32 = ctypes.WinDLL("user32")
    lines = ["/* Generated by scripts/generate-user32-casemap.py.",
             f" * Observable CharUpperBuffW/CharLowerBuffW mappings on Windows {platform.version()}.",
             " * No Windows implementation or NLS-file contents are included.",
             " * Locale-sensitive LCMapString behavior is outside this table. */",
             "#ifndef OSITO_USER32_CASE_DATA_H", "#define OSITO_USER32_CASE_DATA_H", "",
             "typedef struct {", "    uint32_t first, last;", "    int32_t delta;",
             "    uint32_t step;", "} U32_CASE_RANGE;", ""]
    for name, function in (("upper", user32.CharUpperBuffW), ("lower", user32.CharLowerBuffW)):
        data = sample(function)
        lines.append(f"static const U32_CASE_RANGE u32_{name}_ranges[] = {{")
        lines.extend(f"    {{0x{first:06X}, 0x{last:06X}, {delta}, {step}}},"
                     for first, last, delta, step in data)
        lines.extend(["};", ""])
        print(name, len(data), "ranges")
    lines.append("#endif")
    text = "\n".join(lines) + "\n"
    if args.check:
        assert args.output.read_text(encoding="ascii") == text, "reference mapping changed"
    else:
        args.output.write_text(text, encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
