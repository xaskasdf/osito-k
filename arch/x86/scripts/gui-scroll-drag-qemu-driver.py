"""Thumb capture follow-up for the 175% real-input Appearance scenario."""


def drag_button(down):
    gui_qmp("input-send-event", {"events": [{"type": "btn", "data": {
        "down": down, "button": "left"}}]})
    time.sleep(.3)


responsive_move(1236, 260)
drag_button(True)
gui_qemu_capture("12-thumb-grabbed")
assert responsive_region("12-thumb-grabbed") == responsive_region("03-responsive-175-top")
record["passed"].append("grabbing the thumb does not jump the content")
responsive_move(150, 650)
gui_qemu_capture("13-thumb-outside-window")
assert responsive_region("13-thumb-outside-window") == responsive_region("04-responsive-175-scrolled")
record["passed"].append("thumb capture reaches the bottom after leaving System")
drag_button(False)
responsive_move(150, 220)
gui_qemu_capture("14-thumb-released")
assert responsive_region("14-thumb-released") == responsive_region("13-thumb-outside-window")
record["passed"].append("pointer motion after release leaves scroll position unchanged")

responsive_move(1236, 310)
drag_button(True)
responsive_move(150, 10)
gui_qemu_capture("15-thumb-dragged-up")
assert responsive_region("15-thumb-dragged-up") == responsive_region("03-responsive-175-top")
gui_qemu_key("esc")
responsive_move(150, 20)
gui_qemu_capture("16-thumb-escape")
assert responsive_region("16-thumb-escape") == responsive_region("04-responsive-175-scrolled")
drag_button(False)
record["passed"].append("Escape cancels a thumb drag and restores its starting position")

responsive_move(300, 400)
responsive_wheel("wheel-up")
responsive_move(1236, 260)
drag_button(True)
responsive_move(150, 650)
gui_qemu_key("tab", "alt")
responsive_move(150, 180)
drag_button(False)
gui_qemu_key("tab", "alt")
responsive_move(150, 181)
gui_qemu_capture("17-thumb-focus-return")
assert responsive_region("17-thumb-focus-return") == responsive_region("04-responsive-175-scrolled")
record["passed"].append("Alt+Tab cancels thumb capture without moving either window")
responsive_move(300, 400)
responsive_wheel("wheel-up")
gui_qemu_capture("18-thumb-restored")
assert responsive_region("18-thumb-restored") == responsive_region("03-responsive-175-top")
record["passed"].append("wheel navigation resumes after drag cancellation")
