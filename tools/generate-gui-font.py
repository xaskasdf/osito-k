#!/usr/bin/env python3
"""Bake the licensed GUI face at native pixel sizes; no runtime font engine.

Requires Pillow. The checked-in atlas makes normal kernel builds independent
of Python, Pillow and host fonts. Four-bit coverage runs are at most 16 pixels.
"""
import argparse
import hashlib
from pathlib import Path

from PIL import ImageFont

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--font", type=Path, default=Path("gui/fonts/NotoSans-Regular.ttf"))
parser.add_argument("--out", type=Path, default=Path("gui/gui_font_data.h"))
args = parser.parse_args()
scales = (100, 125, 150, 175, 200, 250, 300)
codepoints = list(range(32, 127)) + list(range(160, 256)) + [0x2013, 0x2014, 0x2026]
packed = bytearray()
glyphs = []
faces = []
for scale in scales:
    size = (15 * scale + 50) // 100
    font = ImageFont.truetype(str(args.font), size, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    faces.append((scale, max((22 * scale + 50) // 100, ascent + descent), ascent))
    for cp in codepoints:
        mask, (ox, oy) = font.getmask2(chr(cp), mode="L", anchor="ls")
        width, height = mask.size
        advance = int(font.getlength(chr(cp)) + .5)
        offset = len(packed)
        values = [(value + 8) // 17 for value in bytes(mask)]
        pos = 0
        while pos < len(values):
            count = 1
            while count < 16 and pos + count < len(values) and values[pos + count] == values[pos]:
                count += 1
            packed.append((values[pos] << 4) | (count - 1))
            pos += count
        glyphs.append((offset, width, height, ox, oy, advance))

lines = [
    "/* Generated by tools/generate-gui-font.py; do not edit by hand.",
    " * Noto Sans: SIL Open Font License 1.1, see fonts/LICENSE.txt.",
    " * Source SHA256: " + hashlib.sha256(args.font.read_bytes()).hexdigest(),
    " */",
    "#ifndef OSITO_GUI_FONT_DATA_H",
    "#define OSITO_GUI_FONT_DATA_H",
    "typedef struct { uint32_t offset; uint8_t w, h; int8_t x, y; uint8_t advance; } gui_glyph_t;",
    "typedef struct { uint16_t scale, line, baseline; } gui_face_t;",
    "#define GUI_FACE_GLYPHS " + str(len(codepoints)),
    "static const gui_face_t gui_faces[] = {",
]
lines.extend("    {%d, %d, %d}," % face for face in faces)
lines.extend(["};", "static const gui_glyph_t gui_glyphs[] = {"])
lines.extend("    {%d, %d, %d, %d, %d, %d}," % glyph for glyph in glyphs)
lines.extend(["};", "static const uint8_t gui_coverage[] = {"])
for start in range(0, len(packed), 24):
    lines.append("    " + ",".join("0x%02x" % value for value in packed[start:start + 24]) + ",")
lines.extend(["};", "#endif", ""])
args.out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print("GUI font: %d scales, %d glyphs each, %d coverage bytes" %
      (len(scales), len(codepoints), len(packed)))
